let product = {
    name : "iphone 14",
    company : "Apple",
    price: 120000,
    warranty: "1 year",
    color: "black"
} 
// it gave all keys in our object
console.log(Object.keys(product));
// it gave all values in our object
console.log(Object.values(product));
// it gave all key value pairs in 2d array
console.log(Object.entries(product));
