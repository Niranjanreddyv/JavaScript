let product = {
    name : "iphone",
    company : "Apple",
    price : 120000,
    warranty : "1 Year",
    color : "Black"
}

console.log(Object.keys(product)); // just display key in object
console.log(Object.values(product)); // values display

console.log(Object.entries(product));

console.log(Object.entries(product).length); // no of key value pairs



